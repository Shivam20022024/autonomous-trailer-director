"""Human-readable validation report (validation_report.md)."""
from collections import Counter


def _md_escape(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def write_validation_report(ctx, plans, summary, path, title=None):
    L = []
    w = L.append
    sm, spm = ctx.story_map, ctx.spoiler_map
    w(f"# {title or 'Validation report'}: {sm['title']} ({sm['episode_id']})")
    w("")
    w(f"Run `{summary['run_id']}`, mode `{summary['mode']}`. Generated by the deterministic verifier; "
      "every finding below can be traced to `decision_log.jsonl`.")
    w("")
    w("## Summary")
    w("")
    w("| Trailer | Status | Ready for editor | Duration | Segments | Repairs | Warnings | Est. cost (USD) |")
    w("|---|---|---|---|---|---|---|---|")
    for aud_id, p in plans.items():
        v = p["validation"]
        w(f"| {p['trailer_id']} | **{v['status']}** | {'yes' if p['ready_for_editor'] else 'NO'} | "
          f"{p['duration_seconds']}s (target {p['target_duration_seconds'][0]}-{p['target_duration_seconds'][1]}s) | "
          f"{len(p['segments'])} | {len(p['repair_history'])} | {len(v['warnings'])} | {p['cost']['estimated_usd']:.4f} |")
    w("")
    b = summary["budget"]
    w(f"Budget: {b['model_calls']}/{b['max_model_calls']} model calls, {b['media_minutes']}/{b['max_media_minutes']} "
      f"media minutes, ${b['estimated_usd']:.4f}/${b['max_total_usd']:.2f} "
      f"({'within budget' if b['within_budget'] else 'OVER BUDGET'}).")
    w("")
    w("Cross-trailer distinctness (share of identical clips):")
    w("")
    for row in summary["distinctness"]:
        w(f"- {row['pair'][0]} vs {row['pair'][1]}: {row['shared_clips']} shared clips, Jaccard {row['jaccard']}"
          f"{' (TOO SIMILAR)' if row['too_similar'] else ''}")
    w("")

    w("## What the verification layer rejected before planning")
    w("")
    if sm["rejected_model_claims"] or spm["rejected_model_facts"]:
        for r in sm["rejected_model_claims"]:
            w(f"- Model {r['kind']} claim rejected: `{_md_escape(r['claim'])}`. Reason: {r['reason']}")
        for r in spm["rejected_model_facts"]:
            w(f"- Model protected-fact claim rejected: {r['fact'].get('fact_id')}. Reason: {r['reason']}")
    else:
        w("- No model claims rejected.")
    for f in spm["protected_facts"]:
        if f["source"] == "editorial_tag":
            w(f"- Editorial spoiler tag added protection the model analysis missed: {f['statement']}")
    for m in sm["description_mismatches"]:
        src = "AI" if m["in_ai_description"] else "human"
        w(f"- Description mismatch in {m['scene_id']}: '{m['term']}' only in the {src} description; treated as "
          f"'{m['implied_tag']}' until a human checks the footage.")
    for f in sm["untrusted_text_flags"]:
        w(f"- Instruction-like text in {f['scene_id']} `{f['field']}` was treated as data and ignored "
          f"(matched: {', '.join(f['patterns'])}).")
    w("")
    w("## Audience-insight review")
    w("")
    for aud_id, rows in ctx.bias_review.items():
        for r in rows:
            verdict = "usable" if r["usable"] else "EXCLUDED: " + "; ".join(r["flags"])
            w(f"- `{r['insight_id']}` ({aud_id}) \"{r['claim']}\": {verdict}")
    w("")
    w("## Protected story facts")
    w("")
    for f in spm["protected_facts"]:
        ranges = ", ".join(f"{r['ref']} [{r['start']}-{r['end']}]" for r in f["protected_ranges"])
        w(f"- **{f['fact_id']}** ({f['source']}): {f['statement']} Protected ranges: {ranges}.")
        if f["forbidden_sequences"]:
            w(f"  Forbidden cut orders: {', '.join(' -> '.join(s) for s in f['forbidden_sequences'])}")
    w("")

    for aud_id, p in plans.items():
        v = p["validation"]
        w(f"## {p['trailer_id']}: {p['audience']} ({v['status']})")
        w("")
        w(f"- Promise: {p['audience_promise']}")
        w(f"- Objective: {p['objective']}")
        w(f"- Emotional journey: {' -> '.join(p['emotional_journey'])}")
        w(f"- Music bed: {p['music_plan']['bed_track']}. {p['music_plan'].get('reason', '')}")
        w(f"- Insights used: {', '.join(p['insights_used']) or 'none'}")
        w(f"- Planning source: {p['planning_source'].get('proposal')} ({p['planning_source'].get('model')})")
        w("")
        w("| # | Beat | Source | In | Out | Audio | Subtitle | Text card | Reason |")
        w("|---|---|---|---|---|---|---|---|---|")
        for s in p["segments"]:
            sub = s["subtitle"]["track"] if s.get("subtitle") else "-"
            card = s["text_card"]["text"] if s.get("text_card") else "-"
            w(f"| {s['order']} | {s['beat']} | {s['video']} / {s.get('source_ref') or '-'} | {s['source_in']} | "
              f"{s['source_out']} | {s['audio']}{' + ' + s['music'] if s.get('music') else ''} | {sub} | "
              f"{_md_escape(card)} | {_md_escape(s['reason'])} |")
        w("")
        counts = Counter(a["action"] for a in p["repair_history"])
        w(f"**Repairs** ({', '.join(f'{k} x{n}' for k, n in sorted(counts.items())) or 'none'}):")
        w("")
        for a in p["repair_history"]:
            what = f" {a.get('from')} -> {a.get('to')}" if "from" in a or "to" in a else ""
            w(f"- Round {a['round']}, {a['action']} `{a['segment_id'] or 'plan'}`:{_md_escape(what)}. "
              f"Because: {_md_escape('; '.join(a['because']))}")
        w("")
        if v["errors"]:
            w("**Unresolved errors (plan rejected, not forced through):**")
            w("")
            for e in v["errors"]:
                w(f"- {e['check_id']} `{e['segment_id']}`: {_md_escape(e['message'])}")
            w("")
        w("**Remaining warnings:**")
        w("")
        for e in v["warnings"] or [{"check_id": "-", "segment_id": None, "message": "none"}]:
            w(f"- {e['check_id']} `{e['segment_id'] or 'plan'}`: {_md_escape(e['message'])}")
        w("")
        w("**Human approvals required:**")
        w("")
        for a in p["human_approvals_required"]:
            segs = f" (segments: {', '.join(a['segments'])})" if a["segments"] else ""
            w(f"- [{a['owner']}] {a['approval']}{segs}")
        w("")
        w(f"**Cost:** estimated ${p['cost']['estimated_usd']:.4f}. Lower-cost fallbacks: " +
          "; ".join(f"{f['strategy']} (${f['estimated_usd']:.4f})" for f in p["cost"]["lower_cost_fallback"]))
        w("")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
